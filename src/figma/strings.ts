export function canonicalizePlaceholders(text: string): { canonicalText: string; placeholders: string[] } {
  let counter = 0;
  let out = text.replace(/%(\d+)\$[sdif@]/g, (_match, index: string) => `{arg${index}}`);
  out = out.replace(/%[sdif@]/g, () => `{arg${++counter}}`);
  const placeholders = [...new Set([...out.matchAll(/\{([A-Za-z0-9_]+)\}/g)].map((match) => match[1]!))];
  return { canonicalText: out, placeholders };
}

export function normalizedText(text: string): string {
  return text.normalize("NFC").trim();
}

function shortHash(value: string): string {
  return createHash("sha1").update(value).digest("hex").slice(0, 6);
}

interface CollectContext {
  screen: string;
  ancestors: string[];
}

function elementHintFor(layer: string, context: CollectContext): string {
  if (!isGenericLayerName(layer)) return layer;
  for (let index = context.ancestors.length - 1; index >= 0; index -= 1) {
    const candidate = context.ancestors[index]!;
    if (candidate !== context.screen && !isGenericLayerName(candidate)) return candidate;
  }
  return layer;
}

function collectFromNode(node: FigmaNode, context: CollectContext, out: FigmaTextRecord[]): void {
  const isComponent = node.type === "COMPONENT" || node.type === "COMPONENT_SET";
  const next: CollectContext = isComponent
    ? { screen: node.name || context.screen, ancestors: [] }
    : { screen: context.screen, ancestors: [...context.ancestors, node.name] };

  if (node.type === "TEXT") {
    const raw = typeof node.characters === "string" ? node.characters : "";
    const characters = normalizedText(raw);
    if (characters !== "") {
      const { canonicalText, placeholders } = canonicalizePlaceholders(characters);
      const overrides = node.characterStyleOverrides;
      const mixedStyle = Array.isArray(overrides) && overrides.some((value) => Number(value) !== 0);
      const dynamic = /\$\{|\{\{/.test(characters);
      const layer = node.name || "text";
      out.push({
        nodeId: node.id,
        characters,
        canonicalText,
        screen: context.screen || "app",
        layer,
        element: elementHintFor(layer, context),
        placeholders,
        needsContext: mixedStyle || dynamic,
        needsRename: isGenericLayerName(layer)
      });
    }
    return;
  }

  for (const child of node.children ?? []) {
    collectFromNode(child, next, out);
    if (out.length >= MAX_TEXTS) return;
  }
}

export function collectFigmaTexts(document: FigmaNode): FigmaTextRecord[] {
  const records: FigmaTextRecord[] = [];
  for (const page of document.children ?? []) {
    for (const screen of page.children ?? []) {
      collectFromNode(screen, { screen: screen.name || page.name || "app", ancestors: [] }, records);
      if (records.length >= MAX_TEXTS) return records;
    }
  }
  return records;
}

