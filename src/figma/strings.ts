export function mergeStrings(existing: StringEntry[], records: FigmaTextRecord[]): MergeStringsResult {
  const byNode = new Map(existing.map((entry) => [entry.nodeId, entry]));
  const byKey = new Map(existing.map((entry) => [entry.key, entry]));
  const taken = new Set(existing.map((entry) => entry.key));
  const docNodeIds = new Set(records.map((record) => record.nodeId));

  const entries: StringEntry[] = [];
  const migrations: MigrationSuggestion[] = [];
  const reuseSuggestions: ReuseSuggestion[] = [];
  const rebound = new Set<string>();
  const sorted = [...records].sort((a, b) => a.nodeId.localeCompare(b.nodeId));

  for (const record of sorted) {
    const fingerprint = sourceFingerprintOf(record.canonicalText, record.placeholders);
    const direct = byNode.get(record.nodeId);
    if (direct) {
      const changed = direct.canonicalText !== record.canonicalText;
      entries.push({
        ...direct,
        screen: record.screen,
        layer: record.layer,
        sourceText: record.characters,
        canonicalText: record.canonicalText,
        sourceFingerprint: fingerprint,
        placeholders: record.placeholders,
        lifecycle: record.needsContext ? "needs_context" : changed ? "source_changed" : "active"
      });
      continue;
    }

    const base = deriveCanonicalKey(record);
    const collision = byKey.get(base);
    if (collision && !docNodeIds.has(collision.nodeId)) {
      taken.add(base);
      rebound.add(collision.key);
      migrations.push({
        fromKey: collision.key,
        toKey: base,
        nodeId: record.nodeId,
        reason: "node 身份变化但派生 key 相同：key 已沿用，翻译保持有效",
        status: "suggested"
      });
      entries.push({
        ...collision,
        nodeId: record.nodeId,
        screen: record.screen,
        layer: record.layer,
        sourceText: record.characters,
        canonicalText: record.canonicalText,
        sourceFingerprint: fingerprint,
        placeholders: record.placeholders,
        lifecycle: record.needsContext
          ? "needs_context"
          : collision.canonicalText !== record.canonicalText
            ? "source_changed"
            : "active"
      });
      continue;
    }

    let key = base;
    let duplicated = false;
    if (collision && docNodeIds.has(collision.nodeId)) {
      duplicated = true;
      key = uniquifyKey(base, taken);
      migrations.push({
        fromKey: base,
        toKey: key,
        nodeId: record.nodeId,
        reason: "同一屏幕内派生 key 命中存活节点：已加后缀，需人工重命名",
        status: "suggested"
      });
    } else if (taken.has(base)) {
      duplicated = true;
      key = uniquifyKey(base, taken);
      migrations.push({
        fromKey: base,
        toKey: key,
        nodeId: record.nodeId,
        reason: "同一批次内派生 key 冲突（重复文案节点）：已加后缀，需人工确认",
        status: "suggested"
      });
    }
    taken.add(key);

    const match = entries.find((entry) => entry.canonicalText === record.canonicalText);
    if (match) {
      reuseSuggestions.push({ key, reuseOf: match.key, text: record.canonicalText });
    }

    entries.push({
      key,
      nodeId: record.nodeId,
      screen: record.screen,
      layer: record.layer,
      sourceText: record.characters,
      canonicalText: record.canonicalText,
      sourceFingerprint: fingerprint,
      placeholders: record.placeholders,
      lifecycle: record.needsContext
        ? "needs_context"
        : record.needsRename || duplicated
          ? "needs_rename"
          : "active"
    });
  }

  const unused: string[] = [];
  for (const entry of existing) {
    if (rebound.has(entry.key) || docNodeIds.has(entry.nodeId)) continue;
    if (entries.some((candidate) => candidate.key === entry.key)) continue;
    entries.push({ ...entry, lifecycle: "unused" });
    unused.push(entry.key);
  }

  entries.sort((a, b) => a.key.localeCompare(b.key));
  const sourceChanged = entries.filter((entry) => entry.lifecycle === "source_changed").map((entry) => entry.key);
  return { entries, migrations, reuseSuggestions, unused, sourceChanged };
}

