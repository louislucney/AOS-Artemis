function escapeXml(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function unescapeXml(value: string): string {
  return value
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/\\'/g, "'")
    .replace(/\\"/g, '"')
    .replace(/\\n/g, "\n")
    .replace(/\\t/g, "\t")
    .replace(/\\\\/g, "\\");
}

export function canonicalTextToAndroid(text: string): string {
  const positions = new Map<string, number>();
  let out = text.replace(/\{([A-Za-z0-9_]+)\}/g, (_match, name: string) => {
    if (!positions.has(name)) positions.set(name, positions.size + 1);
    return `%${positions.get(name)}$s`;
  });
  out = out.replace(/%(?!\d+\$s)/g, "%%");
  out = out.replace(/'/g, "\\'");
  if (out.startsWith("@") || out.startsWith("?")) out = `\\${out}`;
  return escapeXml(out);
}

export function canonicalTextToIcu(text: string): string {
  return text;
}

/** ICU → iOS format value (placeholders, `%` escaping). Quote/backslash escapes
 * are applied by the writer (`escapeIos`) so merge comparisons stay logical. */
export function canonicalTextToIos(text: string): string {
  const names = new Set([...text.matchAll(/\{([A-Za-z0-9_]+)\}/g)].map((match) => match[1]!));
  const positions = new Map<string, number>();
  let out = text.replace(/\{([A-Za-z0-9_]+)\}/g, (_match, name: string) => {
    if (!positions.has(name)) positions.set(name, positions.size + 1);
    return names.size > 1 ? `%${positions.get(name)}$@` : "%@";
  });
  out = out.replace(/%(?!\d+\$@|@)/g, "%%");
  return out;
}

function escapeIos(value: string): string {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r");
}

function unescapeIos(value: string): string {
  return value
    .replace(/\\n/g, "\n")
    .replace(/\\r/g, "\r")
    .replace(/\\"/g, '"')
    .replace(/\\\\/g, "\\");
}

interface ExistingAndroidResource {
  value: string;
  file: string;
}

export function parseAndroidStringsFiles(
  rootDir: string,
  excludeFile: string | null
): Map<string, ExistingAndroidResource> {
  const result = new Map<string, ExistingAndroidResource>();
  const files = walkProjectFiles(rootDir, ["app/src/main/res/values*/**/*.xml"]);
  for (const file of files) {
    if (excludeFile && file === excludeFile) continue;
    let text: string;
    try {
      text = fs.readFileSync(path.join(rootDir, file), "utf-8");
    } catch {
      continue;
    }
    for (const match of text.matchAll(/<string\s+name="([^"]+)"[^>]*>([\s\S]*?)<\/string>/g)) {
      const key = match[1]!;
      if (!result.has(key)) result.set(key, { value: unescapeXml(match[2]!.trim()), file });
    }
  }
  return result;
}

export function renderAndroidStrings(
  profile: StackProfile,
  entries: StringEntry[],
  rootDir: string,
  localeDir: string
): ResourceWrite {
  const relativePath = profile.i18n.stringsFile.replace("{localeDir}", localeDir);
  const existingText = readExisting(path.join(rootDir, relativePath));
  const existingOwn = parseAndroidGeneratedContent(existingText);
  const other = parseAndroidStringsFiles(rootDir, relativePath);
  const conflicts: ResourceConflict[] = [];
  const merged = new Map<string, string>();

  for (const [key, value] of existingOwn) merged.set(key, value);

  for (const entry of entries) {
    if (entry.lifecycle === "conflict" || entry.lifecycle === "needs_context") continue;
    const key = platformKey(entry.key, profile.i18n.keyStyle);
    const value = canonicalTextToAndroid(entry.canonicalText);
    const foreign = other.get(key);
    if (foreign) {
      if (unescapeXml(value) !== foreign.value) {
        conflicts.push({ key, existing: foreign.value, incoming: unescapeXml(value) });
      }
      merged.delete(key);
      continue;
    }
    merged.set(key, value);
  }

  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- ${STRING_FILE_MARKER} — do not edit. -->`,
    "<resources>"
  ];
  for (const key of [...merged.keys()].sort()) {
    lines.push(`  <string name="${key}">${merged.get(key)}</string>`);
  }
  lines.push("</resources>", "");
  const content = lines.join("\n");
  const action: ResourceWrite["action"] = existingText === content ? "unchanged" : "written";
  return { relativePath, action, conflicts, content };
}

function parseAndroidGeneratedContent(text: string | null): Map<string, string> {
  const map = new Map<string, string>();
  if (!text) return map;
  for (const match of text.matchAll(/<string\s+name="([^"]+)"[^>]*>([\s\S]*?)<\/string>/g)) {
    map.set(match[1]!, match[2]!.trim());
  }
  return map;
}

export function renderJsonLocale(
  profile: StackProfile,
  entries: StringEntry[],
  rootDir: string,
  locale: string,
  options: { metadata?: boolean } = {}
): ResourceWrite {
  const relativePath = profile.i18n.stringsFile.replace("{locale}", locale);
  const existingText = readExisting(path.join(rootDir, relativePath));
  let existing: Record<string, unknown> = {};
  try {
    const parsed = existingText ? (JSON.parse(existingText) as unknown) : {};
    if (parsed && typeof parsed === "object") existing = parsed as Record<string, unknown>;
  } catch {
    existing = {};
  }
  const conflicts: ResourceConflict[] = [];
  const merged: Record<string, unknown> = { ...existing };

  for (const entry of entries) {
    if (entry.lifecycle === "conflict" || entry.lifecycle === "needs_context") continue;
    const key = platformKey(entry.key, profile.i18n.keyStyle);
    const value = canonicalTextToIcu(entry.canonicalText);
    if (Object.prototype.hasOwnProperty.call(existing, key)) {
      if (existing[key] !== value) {
        conflicts.push({ key, existing: String(existing[key]), incoming: value });
      }
      continue;
    }
    merged[key] = value;
    if (options.metadata === true && entry.placeholders.length > 0) {
      const metadata: Record<string, unknown> = {};
      for (const placeholder of entry.placeholders) metadata[placeholder] = { type: "String" };
      merged[`@${key}`] = { placeholders: metadata };
    }
  }

  const ordered: Record<string, unknown> = {};
  if (typeof merged["@@locale"] === "string") ordered["@@locale"] = merged["@@locale"];
  for (const key of Object.keys(merged)) {
    if (key === "@@locale") continue;
    if (!key.startsWith("@")) ordered[key] = merged[key];
  }
  for (const key of Object.keys(merged)) {
    if (!key.startsWith("@")) continue;
    ordered[key] = merged[key];
  }
  const content = `${JSON.stringify(ordered, null, 2)}\n`;
  const action: ResourceWrite["action"] = existingText === content ? "unchanged" : "written";
  return { relativePath, action, conflicts, content };
}

export function renderFlutterArb(
  profile: StackProfile,
  entries: StringEntry[],
  rootDir: string,
  locale: string
): ResourceWrite {
  return renderJsonLocale(profile, entries, rootDir, locale, { metadata: true });
}

export function renderIosStrings(
  profile: StackProfile,
  entries: StringEntry[],
  rootDir: string,
  locale: string
): ResourceWrite {
  const relativePath = profile.i18n.stringsFile.replace("{locale}", locale);
  const existingText = readExisting(path.join(rootDir, relativePath));
  const existing = parseIosStrings(existingText);
  const conflicts: ResourceConflict[] = [];
  const merged = new Map<string, string>(existing);

  for (const entry of entries) {
    if (entry.lifecycle === "conflict" || entry.lifecycle === "needs_context") continue;
    const key = platformKey(entry.key, profile.i18n.keyStyle);
    const value = canonicalTextToIos(entry.canonicalText);
    const prior = existing.get(key);
    if (prior !== undefined) {
      if (prior !== value) {
        conflicts.push({ key, existing: prior, incoming: value });
      }
      continue;
    }
    merged.set(key, value);
  }

  const lines = [`/* ${STRING_FILE_MARKER} — do not edit. */`];
  for (const [key, value] of [...merged.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    lines.push(`"${key}" = "${escapeIos(value)}";`);
  }
  lines.push("");
  const content = lines.join("\n");
  const action: ResourceWrite["action"] = existingText === content ? "unchanged" : "written";
  return { relativePath, action, conflicts, content };
}

export function parseIosStrings(text: string | null): Map<string, string> {
  const map = new Map<string, string>();
  if (!text) return map;
  for (const match of text.matchAll(/"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;/g)) {
    map.set(unescapeIos(match[1]!), unescapeIos(match[2]!));
  }
  return map;
}

function readExisting(absolute: string): string | null {
  try {
    return fs.readFileSync(absolute, "utf-8");
  } catch {
    return null;
  }
}

export function writeResourceFile(rootDir: string, write: ResourceWrite): ResourceWrite["action"] {
  if (write.action === "unchanged") return "unchanged";
  const absolute = path.join(rootDir, write.relativePath);
  fs.mkdirSync(path.dirname(absolute), { recursive: true });
  fs.writeFileSync(absolute, write.content, "utf-8");
  return "written";
}

