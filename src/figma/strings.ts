export function scanHardcodedStrings(
  rootDir: string,
  stackId: "android-native" | "flutter",
  options: { maxHits?: number } = {}
): HardcodedStringHit[] {
  const hits: HardcodedStringHit[] = [];
  const maxHits = options.maxHits ?? 50;
  const scanFile = (file: string, regex: RegExp): void => {
    let text: string;
    try {
      const stat = fs.statSync(path.join(rootDir, file));
      if (!stat.isFile() || stat.size > MAX_SCAN_BYTES) return;
      text = fs.readFileSync(path.join(rootDir, file), "utf-8");
    } catch {
      return;
    }
    if (text.includes(STRING_FILE_MARKER)) return;
    const lines = text.split(/\r?\n/);
    for (let index = 0; index < lines.length && hits.length < maxHits; index += 1) {
      const line = lines[index]!;
      regex.lastIndex = 0;
      for (const match of line.matchAll(regex)) {
        const value = match[2] ?? match[1] ?? "";
        if (value === "" || value.includes("$")) continue;
        hits.push({ file, line: index + 1, text: value, stack: stackId });
      }
    }
  };

  if (stackId === "android-native") {
    const files = walkProjectFiles(rootDir, ["app/src/main/res/layout*/**/*.xml"]).slice(0, MAX_SCAN_FILES);
    const regex = /android:(?:text|hint|contentDescription)\s*=\s*"([^"]*)"/g;
    for (const file of files) {
      if (hits.length >= maxHits) break;
      scanFile(file, regex);
    }
    return hits.filter((hit) => !hit.text.startsWith("@") && !hit.text.startsWith("?"));
  }

  const files = walkProjectFiles(rootDir, ["lib/**/*.dart"]).slice(0, MAX_SCAN_FILES);
  const regex = /\bText\(\s*(?:const\s+)?(['"])([^'"]*)\1/g;
  for (const file of files) {
    if (hits.length >= maxHits) break;
    scanFile(file, regex);
  }
  return hits;
}

export function stringsExcludeGlobs(profile: StackProfile | null): string[] {
  const globs = ["**/*.arb"];
  if (profile?.i18n.stringsFile) {
    globs.push(profile.i18n.stringsFile.replace("{locale}", "*").replace("{localeDir}", "*"));
  }
  return globs;
}
