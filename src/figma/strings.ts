function slugPart(value: string): string {
  return words(value).slice(0, 4).join("_") || "x";
}

export function deriveCanonicalKey(record: FigmaTextRecord): string {
  const screen = slugPart(record.screen);
  const element = record.needsRename
    ? `text_${shortHash(record.nodeId)}`
    : meaningfulLayerSlug(record.element) ?? `text_${shortHash(record.nodeId)}`;
  return `${screen}.${element}`;
}

function uniquifyKey(base: string, taken: Set<string>): string {
  let key = base;
  let index = 2;
  while (taken.has(key)) {
    key = `${base}_${index}`;
    index += 1;
  }
  return key;
}

export function platformKey(canonicalKey: string, style: CaseStyle): string {
  const parts = canonicalKey.split(".").map((part) => part.split("_")).flat();
  switch (style) {
    case "snake":
      return androidResourceName(parts.join("_"));
    case "kebab":
      return parts.join("-");
    case "pascal":
      return parts.map((part) => `${part[0]!.toUpperCase()}${part.slice(1)}`).join("");
    case "camel":
      return parts
        .map((part, index) => (index === 0 ? part : `${part[0]!.toUpperCase()}${part.slice(1)}`))
        .join("");
  }
}

export function androidResourceName(name: string): string {
  const sanitized = name.toLowerCase().replace(/[^a-z0-9_]/g, "_").replace(/^(\d)/, "_$1");
  if (sanitized.length <= ANDROID_NAME_MAX) return sanitized;
  return `${sanitized.slice(0, ANDROID_NAME_MAX - 7)}_${shortHash(sanitized)}`;
}

export function sourceFingerprintOf(canonicalText: string, placeholders: string[]): string {
  return `sha256:${createHash("sha256").update(`${canonicalText}|${placeholders.join(",")}`).digest("hex")}`;
}

