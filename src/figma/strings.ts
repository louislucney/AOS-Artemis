export function serializeStrings(entries: StringEntry[], sourceLocale: string): string {
  const sorted = [...entries].sort((a, b) => a.key.localeCompare(b.key));
  const lines = [`{`, `  "version": ${STRINGS_FILE_VERSION},`, `  "sourceLocale": ${JSON.stringify(sourceLocale)},`, `  "entries": [`];
  sorted.forEach((entry, index) => {
    const record = {
      key: entry.key,
      nodeId: entry.nodeId,
      screen: entry.screen,
      layer: entry.layer,
      sourceText: entry.sourceText,
      canonicalText: entry.canonicalText,
      sourceFingerprint: entry.sourceFingerprint,
      placeholders: entry.placeholders,
      lifecycle: entry.lifecycle
    };
    lines.push(`    ${JSON.stringify(record)}${index === sorted.length - 1 ? "" : ","}`);
  });
  lines.push("  ]", "}", "");
  return lines.join("\n");
}

export function parseStrings(text: string): StringsFile {
  try {
    const parsed = JSON.parse(text) as Partial<StringsFile>;
    if (!Array.isArray(parsed.entries)) throw new Error("entries 缺失");
    return {
      version: typeof parsed.version === "number" ? parsed.version : STRINGS_FILE_VERSION,
      sourceLocale: typeof parsed.sourceLocale === "string" ? parsed.sourceLocale : "zh",
      entries: parsed.entries as StringEntry[]
    };
  } catch {
    return { version: STRINGS_FILE_VERSION, sourceLocale: "zh", entries: [] };
  }
}

export function loadResolvedConflicts(configDir: string): Set<string> {
  try {
    const raw = fs.readFileSync(path.join(configDir, "design", RESOLUTIONS_FILE), "utf-8");
    const parsed = JSON.parse(raw) as { conflicts?: Record<string, unknown> };
    return new Set(Object.keys(parsed.conflicts ?? {}));
  } catch {
    return new Set();
  }
}

