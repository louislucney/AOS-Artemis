function toAarrggbb(hex8: string): string {
  return `#${hex8.slice(7, 9)}${hex8.slice(1, 7)}`;
}

function cssColor(hex8: string): string {
  return hex8.endsWith("FF") ? hex8.slice(0, 7) : hex8;
}

function camelMember(name: string): string {
  const parts = name.split(/[^A-Za-z0-9]+/).filter(Boolean);
  if (parts.length === 0) return "token";
  return parts
    .map((part, index) => (index === 0 ? part : `${part[0]!.toUpperCase()}${part.slice(1)}`))
    .join("")
    .replace(/[^A-Za-z0-9_$]/g, "");
}

function colorsetJson(hex8: string): Record<string, unknown> {
  const body = hex8.replace(/^#/, "");
  const channel = (pair: string): string => (Number.parseInt(pair, 16) / 255).toFixed(3);
  return {
    colors: [
      {
        color: {
          "color-space": "srgb",
          components: {
            red: channel(body.slice(0, 2)),
            green: channel(body.slice(2, 4)),
            blue: channel(body.slice(4, 6)),
            alpha: channel(body.slice(6, 8))
          }
        },
        idiom: "universal"
      }
    ],
    info: { author: TOKEN_FILE_MARKER, version: 1 }
  };
}

export function resolveTokenValue(token: ColorToken, tokens: ColorToken[]): string {
  if (!token.aliasOf) return token.value;
  const base = tokens.find((candidate) => candidate.name === token.aliasOf);
  return base?.value ?? token.value;
}

export function renderStackTokenFile(profile: StackProfile, tokens: ColorToken[]): StackTokenWrite | null {
  const target = profile.i18n.tokenFile;
  if (!target) return null;
  const sorted = [...tokens].sort((a, b) => a.name.localeCompare(b.name));

  if (profile.id === "android-native") {
    const lines = [
      '<?xml version="1.0" encoding="utf-8"?>',
      `<!-- ${TOKEN_FILE_MARKER} — do not edit. -->`,
      "<resources>"
    ];
    for (const token of sorted) {
      const value = resolveTokenValue(token, tokens);
      const resource = token.name.replace(/\./g, "_").replace(/[^a-z0-9_]/g, "_");
      lines.push(`  <!-- ${token.name} -->`);
      lines.push(`  <color name="${resource}">${toAarrggbb(value)}</color>`);
    }
    lines.push("</resources>", "");
    return { relativePath: target, content: lines.join("\n"), format: "android-xml" };
  }

  if (profile.id === "flutter") {
    const lines = [
      `// ${TOKEN_FILE_MARKER} — do not edit.`,
      "import 'package:flutter/material.dart';",
      "",
      "abstract final class AosTokens {"
    ];
    for (const token of sorted) {
      const value = resolveTokenValue(token, tokens);
      lines.push(`  /// ${token.name}`);
      lines.push(`  static const Color ${camelMember(token.name)} = Color(0x${toAarrggbb(value).slice(1)});`);
    }
    lines.push("}", "");
    return { relativePath: target, content: lines.join("\n"), format: "dart" };
  }

  if (profile.id === "web") {
    const lines = [`/* ${TOKEN_FILE_MARKER} — do not edit. */`, ":root {"];
    for (const token of sorted) {
      const value = resolveTokenValue(token, tokens);
      lines.push(`  --${token.name.replace(/[._]/g, "-")}: ${cssColor(value)};`);
    }
    lines.push("}", "");
    return { relativePath: target, content: lines.join("\n"), format: "css" };
  }

  if (profile.id === "ios-native") {
    const lines = [`// ${TOKEN_FILE_MARKER} — do not edit.`, "import SwiftUI", "", "enum AosTokens {"];
    const extraFiles: StackTokenFileWrite[] = [];
    for (const token of sorted) {
      const value = resolveTokenValue(token, tokens);
      lines.push(`  /// ${token.name}`);
      lines.push(`  static let ${camelMember(token.name)} = Color("${token.name}")`);
      extraFiles.push({
        relativePath: path.posix.join(
          "Resources",
          "Colors.xcassets",
          `${token.name}.colorset`,
          "Contents.json"
        ),
        content: `${JSON.stringify(colorsetJson(value), null, 2)}\n`,
        format: "xcassets-json"
      });
    }
    lines.push("}", "");
    return { relativePath: target, content: lines.join("\n"), format: "swift", extraFiles };
  }

  const lines = [`/* ${TOKEN_FILE_MARKER} — do not edit. */`, "export const aosTokens = {"];
  for (const token of sorted) {
    const value = resolveTokenValue(token, tokens);
    lines.push(`  ${JSON.stringify(token.name)}: ${JSON.stringify(cssColor(value))},`);
  }
  lines.push("} as const;", "");
  return { relativePath: target, content: lines.join("\n"), format: "ts" };
}

export function contentHasTokenMarker(content: string): boolean {
  return content.includes(TOKEN_FILE_MARKER);
}

export interface StackTokenWriteResult {
  relativePath: string;
  action: "written" | "unchanged" | "planned" | "skipped_unmanaged";
  files?: Array<{ relativePath: string; action: StackTokenWriteResult["action"] }>;
}

/** Idempotent stack-file writer shared by the Figma and pen token importers:
 * same content → `unchanged`; unmanaged file (no generated marker) is left alone
 * unless `overwrite`; `dryRun` reports the planned action without touching disk. */
export function writeStackTokenFile(
  rootDir: string,
  write: StackTokenWrite,
  options: { overwrite?: boolean; dryRun?: boolean } = {}
): StackTokenWriteResult {
  const main = writeStackTokenFileSingle(rootDir, write, options);
  const extras = (write.extraFiles ?? []).map((file) =>
    writeStackTokenFileSingle(rootDir, file, options)
  );
  if (extras.length === 0) return main;
  return {
    ...main,
    files: [main, ...extras].map(({ relativePath, action }) => ({ relativePath, action }))
  };
}

export function skippedTokenFiles(result: StackTokenWriteResult | null): string[] {
  if (!result) return [];
  return [
    ...(result.action === "skipped_unmanaged" ? [result.relativePath] : []),
    ...(result.files ?? [])
      .filter((file) => file.action === "skipped_unmanaged")
      .map((file) => file.relativePath)
  ];
}

function writeStackTokenFileSingle(
  rootDir: string,
  write: StackTokenFileWrite,
  options: { overwrite?: boolean; dryRun?: boolean }
): StackTokenWriteResult {
  const absolute = path.join(rootDir, write.relativePath);
  if (!fs.existsSync(absolute)) {
    if (options.dryRun !== true) {
      fs.mkdirSync(path.dirname(absolute), { recursive: true });
      fs.writeFileSync(absolute, write.content, "utf-8");
      return { relativePath: write.relativePath, action: "written" };
    }
    return { relativePath: write.relativePath, action: "planned" };
  }
  const current = fs.readFileSync(absolute, "utf-8");
  if (current === write.content) return { relativePath: write.relativePath, action: "unchanged" };
  if (!contentHasTokenMarker(current) && options.overwrite !== true) {
    return { relativePath: write.relativePath, action: "skipped_unmanaged" };
  }
  if (options.dryRun !== true) {
    fs.writeFileSync(absolute, write.content, "utf-8");
    return { relativePath: write.relativePath, action: "written" };
  }
  return { relativePath: write.relativePath, action: "planned" };
}

