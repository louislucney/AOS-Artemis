export function loadTokenOverrides(configDir: string): Record<string, string> {
  const filePath = path.join(configDir, "design", TOKEN_NAMES_FILE);
  try {
    const parsed = JSON.parse(fs.readFileSync(filePath, "utf-8")) as { overrides?: unknown };
    const overrides = parsed.overrides;
    if (!overrides || typeof overrides !== "object") return {};
    const normalized: Record<string, string> = {};
    for (const [key, value] of Object.entries(overrides as Record<string, unknown>)) {
      const color = normalizeHexColor(key);
      if (!color || typeof value !== "string") continue;
      const name = value.trim();
      if (!/^color(\.[a-z0-9_-]+)+$/i.test(name)) continue;
      normalized[color] = name;
    }
    return normalized;
  } catch {
    return {};
  }
}

export function scanHardcodedColors(
  rootDir: string,
  options: { excludeGlobs?: string[]; maxHits?: number } = {}
): HardcodedColorHit[] {
  const exclude = (options.excludeGlobs ?? []).map(globToRegExp);
  const files = walkProjectFiles(rootDir, CODE_GLOBS).slice(0, MAX_SCAN_FILES);
  const hits: HardcodedColorHit[] = [];
  const maxHits = options.maxHits ?? 50;
  for (const file of files) {
    if (exclude.some((regex) => regex.test(file))) continue;
    let text: string;
    try {
      const stat = fs.statSync(path.join(rootDir, file));
      if (!stat.isFile() || stat.size > MAX_SCAN_BYTES) continue;
      text = fs.readFileSync(path.join(rootDir, file), "utf-8");
    } catch {
      continue;
    }
    if (text.includes("\u0000") || contentHasTokenMarker(text) || text.includes(TOKEN_FILE_MARKER)) {
      continue;
    }
    const lines = text.split(/\r?\n/);
    for (let index = 0; index < lines.length && hits.length < maxHits; index += 1) {
      const line = lines[index]!;
      for (const match of line.matchAll(/#([0-9a-fA-F]{3,8})\b/g)) {
        const normalized = normalizeHexColor(match[1]!);
        if (!normalized) continue;
        hits.push({ file, line: index + 1, value: normalized });
      }
      for (const match of line.matchAll(/\b0x([0-9a-fA-F]{8})\b/g)) {
        const raw = match[1]!.toUpperCase();
        hits.push({ file, line: index + 1, value: `#${raw.slice(2)}${raw.slice(0, 2)}` });
      }
    }
    if (hits.length >= maxHits) break;
  }
  return hits;
}

export function tokenFingerprint(tokens: ColorToken[]): string {
  return fingerprint(tokens.map((token) => `${token.name}=${token.value}`).join("|"));
}
