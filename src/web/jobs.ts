interface SelectionFailure {
  ok: false;
  code: WebAssignmentFailureCode;
  message: string;
}

interface SelectionSuccess {
  ok: true;
  hostId: string;
  deviceSerial: string;
  score: number;
}

type Selection = SelectionSuccess | SelectionFailure;

function runnerCandidates(runners: WebRunnerRecord[]): WebRunnerCandidate[] {
  return runners.map((runner) => ({
    id: runner.id,
    hostId: runner.hostId,
    hostname: runner.hostname,
    platforms: runner.platforms,
    devices: runner.devices,
    tools: runner.tools,
    lastSeenAt: runner.lastSeenAt
  }));
}

function assignmentError(
  code: string,
  message: string,
  nowMs: number
): WebJobAssignmentError {
  return { code, message, at: new Date(nowMs).toISOString() };
}

function specRecord(spec: WebJobSpec): Record<string, unknown> {
  return spec as unknown as Record<string, unknown>;
}

function assetLabel(kind: string): string {
  if (kind === "excel") return "Excel";
  if (kind === "package") return "安装包";
  if (kind === "materials") return "测试资料";
  return "脚本集";
}

async function loadAsset(
  store: ProjectStore,
  rootPath: string,
  kind: WebAssetRecord["kind"],
  id: string | null
): Promise<WebAssetRecord | null> {
  if (id === null) return null;
  const asset = await store.getWebAsset(rootPath, id);
  if (asset === null) {
    throw new WebJobDispatchError("asset-not-found", `${assetLabel(kind)}资产不存在：${id}`);
  }
  if (asset.kind !== kind) {
    throw new WebJobDispatchError(
      "asset-kind-mismatch",
      `资产 ${id} 类型为 ${asset.kind}，此处要求 ${kind}（${assetLabel(kind)}）`
    );
  }
  return asset;
}

async function selectForSpec(
  input: WebJobContext & {
    spec: WebJobSpec;
    taskId: string | null;
    nowMs: number;
    runnerTtlMs: number;
    rng?: () => number;
    /** 队列暂停的 host：不参与新的选机/绑定。 */
    excludeHostIds?: Set<string>;
  }
): Promise<Selection> {
  const [runners, leases] = await Promise.all([
    input.store.listWebRunners(),
    input.store.listDeviceLeases()
  ]);
  const candidates = runnerCandidates(runners).filter(
    (runner) => !(input.excludeHostIds?.has(runner.hostId) ?? false)
  );
  const result: WebAssignmentResult = selectWebAssignment({
    runners: candidates,
    leases,
    request: {
      assignment: input.spec.assignment,
      devicePinned: input.spec.devicePinned,
      targetHostId: input.spec.targetHostId,
      deviceSerial: input.spec.deviceSerial,
      requirements: input.spec.requirements
    },
    nowMs: input.nowMs,
    runnerTtlMs: input.runnerTtlMs,
    taskId: input.taskId,
    ...(input.rng === undefined ? {} : { rng: input.rng })
  });
  return result;
}

function pendingSpec(
  spec: WebJobSpec,
  failure: SelectionFailure,
  nowMs: number
): WebJobSpec {
  return {
    ...spec,
    targetHostId: spec.assignment === "manual" ? spec.targetHostId : null,
    deviceSerial: spec.assignment === "manual" && spec.devicePinned ? spec.deviceSerial : null,
    deviceLeaseId: null,
    assignmentError: assignmentError(failure.code, failure.message, nowMs)
  };
}

async function createPendingTask(
  input: CreateWebJobInput,
  spec: WebJobSpec
): Promise<RegressionTaskRecord> {
  return input.store.createRegressionTask({
    rootPath: input.rootPath,
    refs: [],
    platforms: [spec.requirements.platform],
    baseline: "latest",
    createdBy: input.createdBy ?? null,
    targetHostId: spec.targetHostId,
    priority: input.priority,
    jobSpec: specRecord(spec),
    deviceSerial: spec.deviceSerial,
    deviceLeaseId: null
  });
}

const DEFAULT_SCRIPT_GEN_TIMEOUT_MS = 30_000;

function scriptGenerationTimeoutMs(
  env: NodeJS.ProcessEnv,
  explicit: number | undefined
): number {
  if (explicit !== undefined && Number.isFinite(explicit) && explicit >= 0) {
    return Math.floor(explicit);
  }
  const raw = Number.parseInt(env.AOS_WEB_SCRIPT_GEN_TIMEOUT_MS ?? "", 10);
  if (Number.isFinite(raw) && raw >= 0) return raw;
  return DEFAULT_SCRIPT_GEN_TIMEOUT_MS;
}

function scriptStats(asset: WebAssetRecord): {
  ready: number;
  partial: number;
  unresolved: number;
  runnable: number;
} {
  const num = (key: string): number => {
    const value = asset.metadata?.[key];
    return typeof value === "number" && Number.isFinite(value) ? value : 0;
  };
  return {
    ready: num("ready"),
    partial: num("partial"),
    unresolved: num("unresolved"),
    runnable: num("runnable")
  };
}

interface GeneratedScript {
  asset: WebAssetRecord;
  created: boolean;
  ready: number;
  partial: number;
  unresolved: number;
  runnable: number;
}

async function generateScriptForJob(input: {
  store: ProjectStore;
  rootPath: string;
  excelAssetId: string;
  packageAssetId: string;
  platform: "android" | "ios";
  appPackage: string | null;
  uploadedBy: string | null;
  timeoutMs: number;
}): Promise<GeneratedScript> {
  try {
    const result = await generateScriptSetForProject({
      store: input.store,
      rootPath: input.rootPath,
      excelAssetId: input.excelAssetId,
      packageAssetId: input.packageAssetId,
      platform: input.platform,
      appId: input.appPackage,
      preconditionMode: "auto",
      bestEffort: true,
      inferNavigationTap: true,
      uploadedBy: input.uploadedBy,
      ...(input.timeoutMs === 0 ? {} : { timeoutMs: input.timeoutMs })
    });
    if (result.asset === null) {
      throw new WebJobDispatchError(
        "script-generation-failed",
        "脚本生成未返回 assets 资产（dry-run 不应发生在下发路径）"
      );
    }
    return {
      asset: result.asset,
      created: result.created,
      ready: result.ready,
      partial: result.partial,
      unresolved: result.unresolved,
      runnable: result.runnable
    };
  } catch (error) {
    if (error instanceof WebJobDispatchError) throw error;
    if (error instanceof ScriptGenerationTimeoutError) {
      throw new WebJobDispatchError("script-generation-timeout", error.message);
    }
    if (error instanceof ScriptGenerationError || error instanceof ScriptSetStoreError) {
      throw new WebJobDispatchError("script-generation-failed", error.message);
    }
    throw new WebJobDispatchError(
      "script-generation-failed",
      `生成脚本集失败：${errorMessage(error)}`
    );
  }
}

/**
 * 创建 web 任务：校验组合/资产/脚本集，选机并预占设备。
 * manual 目标 host 离线或暂无候选时允许建 pending（保留 targetHostId，钉设备再保留 serial，无 lease）。
 */
export async function createWebJob(input: CreateWebJobInput): Promise<CreateWebJobResult> {
  const env = input.env ?? process.env;
  const combination = assertWebJobCombination(input);

  const webProject = await input.store.getWebProject(input.rootPath);
  if (webProject === null) {
    throw new WebJobDispatchError(
      "project-not-found",
      `不是托管 Web 项目：${input.rootPath}`
    );
  }
  if (webProject.status !== "active") {
    throw new WebJobDispatchError(
      "project-archived",
      `项目已归档（status=${webProject.status}）：${webProject.name}`
    );
  }
  const project = await input.store.getProjectByPath(input.rootPath);
  if (project === null) {
    throw new WebJobDispatchError("project-not-found", `项目未注册：${input.rootPath}`);
  }

  const excel = await loadAsset(input.store, input.rootPath, "excel", input.excelAssetId);
  const pkg = await loadAsset(input.store, input.rootPath, "package", input.packageAssetId);
  const materials = await loadAsset(
    input.store,
    input.rootPath,
    "materials",
    typeof input.materialsAssetId === "string" && input.materialsAssetId.trim() !== ""
      ? input.materialsAssetId.trim()
      : null
  );
  const scriptId =
    typeof input.scriptSetId === "string" && input.scriptSetId.trim() !== ""
      ? input.scriptSetId.trim()
      : null;
  let script: WebAssetRecord | null = await loadAsset(
    input.store,
    input.rootPath,
    "scripts",
    scriptId
  );
  const warnings: string[] = [];
  let autoGenerated = false;
  let rebuiltFrom: string | null = null;
  let scriptCreated = false;
  let stats = script === null ? null : scriptStats(script);
  const timeoutMs = scriptGenerationTimeoutMs(env, input.scriptGenerationTimeoutMs);
  const generate = async (): Promise<GeneratedScript> =>
    generateScriptForJob({
      store: input.store,
      rootPath: input.rootPath,
      excelAssetId: excel!.id,
      packageAssetId: pkg!.id,
      platform: combination.requirements.platform,
      appPackage: webProject.appPackage ?? null,
      uploadedBy: input.createdBy ?? null,
      timeoutMs
    });

  if (script !== null) {
    let matchFailure: WebJobDispatchError | null = null;
    try {
      assertScriptSetMatch({
        script,
        excelAssetId: excel!.id,
        packageAssetId: pkg!.id,
        platform: combination.requirements.platform,
        allowStaleScript: false
      });
    } catch (error) {
      if (
        error instanceof WebJobDispatchError &&
        (error.code === "script-set-mismatch" || error.code === "script-set-unverified")
      ) {
        matchFailure = error;
      } else {
        throw error;
      }
    }
    if (matchFailure !== null) {
      if (input.allowStaleScript === true) {
        warnings.push("stale-script");
      } else {
        const previous = script.id;
        let generated: GeneratedScript;
        try {
          generated = await generate();
        } catch (error) {
          throw new WebJobDispatchError(
            "script-set-rebuild-failed",
            `脚本集 ${previous} 过期且重建失败：${errorMessage(error)}`
          );
        }
        script = generated.asset;
        scriptCreated = generated.created;
        stats = {
          ready: generated.ready,
          partial: generated.partial,
          unresolved: generated.unresolved,
          runnable: generated.runnable
        };
        rebuiltFrom = previous;
        warnings.push("script-set-rebuilt");
        try {
          assertScriptSetMatch({
            script,
            excelAssetId: excel!.id,
            packageAssetId: pkg!.id,
            platform: combination.requirements.platform,
            allowStaleScript: false
          });
        } catch (error) {
          throw new WebJobDispatchError(
            "script-set-rebuild-failed",
            `重建后的脚本集仍与任务资产不匹配：${errorMessage(error)}`
          );
        }
      }
    }
  } else if (combination.executionMode === "maestro") {
    const generated = await generate();
    script = generated.asset;
    scriptCreated = generated.created;
    autoGenerated = true;
    stats = {
      ready: generated.ready,
      partial: generated.partial,
      unresolved: generated.unresolved,
      runnable: generated.runnable
    };
  }

  const allowPartialUnresolved = input.allowPartialUnresolved !== false;
  if (script !== null && stats !== null) {
    if (stats.unresolved > 0 && !allowPartialUnresolved) {
      throw new WebJobDispatchError(
        "script-set-incomplete",
        `脚本集 ${script.id} 有 ${stats.unresolved} 个 unresolved 用例；显式关闭了部分下发，请重新生成/修正 Excel，或允许部分下发`
      );
    }
    if (stats.unresolved > 0 && (autoGenerated || rebuiltFrom !== null)) {
      warnings.push(`script-set-unresolved:${stats.unresolved}`);
    }
  }
  const scriptInfo: WebJobScriptInfo | null =
    script === null || stats === null
      ? null
      : {
          id: script.id,
          autoGenerated,
          rebuiltFrom,
          created: scriptCreated,
          ready: stats.ready,
          partial: stats.partial,
          unresolved: stats.unresolved,
          runnable: stats.runnable
        };

  const snapshot: WebAssetSnapshot[] = buildAssetSnapshot(
    [excel!, pkg!, materials, script].filter((asset): asset is WebAssetRecord => asset !== null)
  );
  const retry = typeof input.retry === "number" && input.retry >= 0 ? Math.trunc(input.retry) : 0;
  const spec: WebJobSpec = {
    kind: "web-test",
    assignment: combination.assignment,
    devicePinned: combination.devicePinned,
    targetHostId: combination.targetHostId,
    deviceSerial: combination.deviceSerial,
    requirements: combination.requirements,
    deviceLeaseId: null,
    excelAssetId: excel!.id,
    packageAssetId: pkg!.id,
    materialsAssetId: materials?.id ?? null,
    scriptSetId: script?.id ?? null,
    executionMode: combination.executionMode,
    caseFilter: normalizeCaseFilter(input.caseFilter),
    retry,
    allowStaleScript: input.allowStaleScript === true,
    allowPartialUnresolved,
    assetSnapshot: snapshot,
    reassignCount: 0,
    assignmentError: null
  };

  const nowMs = input.nowMs ?? Date.now();
  const runnerTtlMs = input.runnerTtlMs ?? runnerTtlFrom(env);
  const reservationTtlMs = input.reservationTtlMs ?? deviceLeaseTtlMs(env);
  const selection = await selectForSpec({
    store: input.store,
    env,
    spec,
    taskId: null,
    nowMs,
    runnerTtlMs,
    rng: input.rng
  });

  if (!selection.ok) {
    if (selection.code === "device-busy" && spec.assignment === "manual" && spec.devicePinned) {
      throw new WebJobDispatchError("device-busy", selection.message);
    }
    if (
      spec.assignment === "manual" &&
      spec.devicePinned &&
      selection.code === "requirements-unmet"
    ) {
      throw new WebJobDispatchError("device-not-on-host", selection.message);
    }
    if (spec.assignment === "auto" && selection.code === "requirements-unmet") {
      throw new WebJobDispatchError("invalid-requirements", selection.message);
    }
    const pending = pendingSpec(spec, selection, nowMs);
    const task = await createPendingTask(input, pending);
    return {
      task,
      assignment: null,
      pendingReason: selection.message,
      script: scriptInfo,
      warnings
    };
  }

  const leaseId = webJobLeaseId(selection.hostId, selection.deviceSerial);
  const boundSpec: WebJobSpec = {
    ...spec,
    targetHostId: selection.hostId,
    deviceSerial: selection.deviceSerial,
    deviceLeaseId: leaseId
  };
  // N3：创建窗口内的 pending 任务带 binding 标记，assign/reassign 必须跳过。
  const bindingSpec: WebJobSpec = { ...boundSpec, binding: true };
  // 安全顺序：先建任务（顶层 serial/lease 为空，claim 不可命中）→ 取租约 → CAS 绑定。
  const task = await input.store.createRegressionTask({
    rootPath: input.rootPath,
    refs: [],
    platforms: [spec.requirements.platform],
    baseline: "latest",
    createdBy: input.createdBy ?? null,
    targetHostId: selection.hostId,
    priority: input.priority,
    jobSpec: specRecord(bindingSpec),
    deviceSerial: null,
    deviceLeaseId: null
  });

  const cleanup = async (message: string): Promise<void> => {
    await input.store.releaseDeviceLeases({
      hostId: selection.hostId,
      taskId: task.id,
      serials: [selection.deviceSerial]
    });
    await input.store.cancelRegressionTask({
      rootPath: input.rootPath,
      taskId: task.id,
      source: "panel",
      actor: input.createdBy ?? "web-job",
      actorHostId: null,
      note: message
    });
    await input.store.updateRegressionTask(input.rootPath, task.id, {
      deviceSerial: null,
      deviceLeaseId: null,
      jobSpec: specRecord({
        ...boundSpec,
        deviceLeaseId: null,
        assignmentError: assignmentError("device-busy", message, nowMs)
      }),
      expectStatuses: ["cancelled"]
    });
  };

  const leased = await input.store.acquireDeviceLeases({
    hostId: selection.hostId,
    taskId: task.id,
    projectId: project.id,
    serials: [selection.deviceSerial],
    ttlMs: reservationTtlMs,
    at: new Date(nowMs).toISOString()
  });
  if (!leased.ok) {
    const message = `设备 ${selection.deviceSerial} 已被其他任务占用（${leased.busy.join(",")}）`;
    await cleanup(message);
    throw new WebJobDispatchError("device-busy", message);
  }

  const bound = await input.store.updateRegressionTask(input.rootPath, task.id, {
    deviceSerial: selection.deviceSerial,
    deviceLeaseId: leaseId,
    jobSpec: specRecord(boundSpec),
    expectStatuses: ["pending"],
    expectDeviceSerialEmpty: true
  });
  if (!bound) {
    const current = await input.store.getRegressionTask(input.rootPath, task.id);
    if (
      current !== null &&
      current.deviceSerial === selection.deviceSerial &&
      current.deviceLeaseId === leaseId
    ) {
      return {
        task: current,
        assignment: {
          hostId: selection.hostId,
          deviceSerial: selection.deviceSerial,
          score: selection.score
        },
        pendingReason: null,
        script: scriptInfo,
        warnings
      };
    }
    const message = `设备 ${selection.deviceSerial} 绑定失败（任务已被并发取消/改派）`;
    await cleanup(message);
    throw new WebJobDispatchError("device-busy", message);
  }

  const stored = (await input.store.getRegressionTask(input.rootPath, task.id)) ?? task;
  return {
    task: stored,
    assignment: {
      hostId: selection.hostId,
      deviceSerial: selection.deviceSerial,
      score: selection.score
    },
    pendingReason: null,
    script: scriptInfo,
    warnings
  };
}

async function bindPendingTask(
  input: AssignPendingWebJobsInput,
  entry: { task: RegressionTaskRecord; rootPath: string },
  spec: WebJobSpec,
  nowMs: number,
  runnerTtlMs: number,
  reservationTtlMs: number,
  writeError = true,
  excludeHostIds?: Set<string>
): Promise<boolean> {
  const selection = await selectForSpec({
    store: input.store,
    env: input.env,
    spec,
    taskId: entry.task.id,
    nowMs,
    runnerTtlMs,
    rng: input.rng,
    ...(excludeHostIds === undefined ? {} : { excludeHostIds })
  });
  if (!selection.ok) {
    const message = selection.message;
    if (writeError && spec.assignmentError?.message !== message) {
      await input.store.updateRegressionTask(entry.rootPath, entry.task.id, {
        jobSpec: specRecord({
          ...spec,
          assignmentError: assignmentError(selection.code, message, nowMs)
        }),
        expectStatuses: ["pending"]
      });
    }
    return false;
  }

  const project = await input.store.getProjectByPath(entry.rootPath);
  const leased = await input.store.acquireDeviceLeases({
    hostId: selection.hostId,
    taskId: entry.task.id,
    projectId: project?.id ?? null,
    serials: [selection.deviceSerial],
    ttlMs: reservationTtlMs,
    at: new Date(nowMs).toISOString()
  });
  if (!leased.ok) {
    await input.store.updateRegressionTask(entry.rootPath, entry.task.id, {
      jobSpec: specRecord({
        ...spec,
        assignmentError: assignmentError(
          "device-busy",
          `设备预占冲突：${leased.busy.join(",")}`,
          nowMs
        )
      }),
      expectStatuses: ["pending"]
    });
    return false;
  }

  const leaseId = webJobLeaseId(selection.hostId, selection.deviceSerial);
  const updated = await input.store.updateRegressionTask(entry.rootPath, entry.task.id, {
    targetHostId: selection.hostId,
    deviceSerial: selection.deviceSerial,
    deviceLeaseId: leaseId,
    jobSpec: specRecord({
      ...spec,
      targetHostId: selection.hostId,
      deviceSerial: selection.deviceSerial,
      deviceLeaseId: leaseId,
      assignmentError: null
    }),
    expectStatuses: ["pending"],
    ...(entry.task.deviceSerial === null ? { expectDeviceSerialEmpty: true } : {})
  });
  if (!updated) {
    await input.store.releaseDeviceLeases({
      hostId: selection.hostId,
      taskId: entry.task.id,
      serials: [selection.deviceSerial]
    });
    return false;
  }
  return true;
}

/** 给 pending web 任务选机并预占；包含「已钉 serial 但无有效租约」的等待任务。返回成功绑定条数。 */
export async function assignPendingWebJobs(input: AssignPendingWebJobsInput): Promise<number> {
  const env = input.env ?? process.env;
  const reservationTtlMs = input.reservationTtlMs ?? deviceLeaseTtlMs(env);
  const pausedHostIds = await pausedWebHostIds(input.store);
  const pending = await input.store.listPendingWebJobs();
  let bound = 0;
  for (const entry of pending) {
    const spec = parseWebJobSpec(entry.task.jobSpec);
    if (spec === null) continue;
    if (spec.binding === true) continue;
    if ((spec.reassignCount ?? 0) > WEB_JOB_REASSIGN_LIMIT) continue;

    if (entry.task.deviceSerial !== null) {
      const leases = await input.store.listDeviceLeases();
      const live = leases.some(
        (lease) =>
          lease.taskId === entry.task.id &&
          lease.hostId === entry.task.targetHostId &&
          lease.serial === entry.task.deviceSerial &&
          Date.parse(lease.expiresAt) > input.nowMs
      );
      if (live) continue;
    }

    const desired: WebJobSpec =
      entry.task.deviceSerial === null
        ? spec
        : {
            ...spec,
            targetHostId: entry.task.targetHostId ?? spec.targetHostId,
            deviceSerial: entry.task.deviceSerial,
            devicePinned: spec.assignment === "manual" ? true : spec.devicePinned
          };
    const ok = await bindPendingTask(
      input,
      entry,
      desired,
      input.nowMs,
      input.runnerTtlMs,
      reservationTtlMs,
      entry.task.deviceSerial === null,
      pausedHostIds
    );
    if (ok) bound += 1;
  }
  return bound;
}

/**
 * 回收过期/离线预占：auto 回全局池重选；manual 未钉设备保留 host 重选；
 * manual 钉设备保留 host+serial 等待（在线时尝试重新预占）。改派超过 3 次判 failed。
 */
export async function reassignExpiredWebJobs(
  input: ReassignExpiredWebJobsInput
): Promise<number> {
  const env = input.env ?? process.env;
  const runnerTtlMs = input.runnerTtlMs ?? runnerTtlFrom(env);
  const reservationTtlMs = input.reservationTtlMs ?? input.leaseTtlMs;
  const [pending, leases, runners, pausedHostIds] = await Promise.all([
    input.store.listPendingWebJobs(),
    input.store.listDeviceLeases(),
    input.store.listWebRunners(),
    pausedWebHostIds(input.store)
  ]);
  let processed = 0;
  for (const entry of pending) {
    if (entry.task.deviceSerial !== null) {
      const spec = parseWebJobSpec(entry.task.jobSpec);
      if (spec === null) continue;
      if (spec.binding === true) continue;
      const hostId = entry.task.targetHostId;
      if (hostId === null) continue;
      // 队列暂停：保留绑定/等待，不改派、不计 reassignCount。
      if (pausedHostIds.has(hostId)) continue;
      const lease = leases.find(
        (row) =>
          row.hostId === hostId &&
          row.serial === entry.task.deviceSerial &&
          row.taskId === entry.task.id
      );
      const leaseExpired =
        lease === undefined || !(Date.parse(lease.expiresAt) > input.nowMs);
      const runner = runners.find((row) => row.hostId === hostId);
      const online = runner !== undefined && isRunnerOnline(runner.lastSeenAt, input.nowMs, runnerTtlMs);
      if (!leaseExpired && online) continue;

      processed += 1;
      const reason = leaseExpired ? "设备预占租约已过期" : `执行机 ${hostId} 离线`;
      await input.store.releaseDeviceLeases({
        hostId,
        taskId: entry.task.id,
        serials: [entry.task.deviceSerial]
      });

      if (spec.assignment === "manual" && spec.devicePinned) {
        // 钉设备只等待，不计入 reassignCount（C1）：单独 pinnedWaitCount + 明确告警。
        const pinnedWaitCount = (spec.pinnedWaitCount ?? 0) + 1;
        const baseSpec: WebJobSpec = {
          ...spec,
          deviceLeaseId: null,
          pinnedWaitCount,
          assignmentError: null
        };
        await input.store.updateRegressionTask(entry.rootPath, entry.task.id, {
          deviceLeaseId: null,
          jobSpec: specRecord(baseSpec),
          expectStatuses: ["pending"]
        });
        if (online) {
          // 绑定失败会由 bindPendingTask 写入真实原因（device-busy 等），不覆盖成 host-offline。
          await bindPendingTask(
            {
              store: input.store,
              env,
              nowMs: input.nowMs,
              runnerTtlMs,
              reservationTtlMs,
              rng: input.rng
            },
            entry,
            baseSpec,
            input.nowMs,
            runnerTtlMs,
            reservationTtlMs,
            true,
            pausedHostIds
          );
          continue;
        }
        await input.store.updateRegressionTask(entry.rootPath, entry.task.id, {
          jobSpec: specRecord({
            ...baseSpec,
            assignmentError: assignmentError(
              "host-offline",
              `${reason}；设备已钉住，等待 host/设备恢复（第 ${pinnedWaitCount} 次检查，不计改派）`,
              input.nowMs
            )
          }),
          expectStatuses: ["pending"]
        });
        continue;
      }

      const reassignCount = (spec.reassignCount ?? 0) + 1;

      if (reassignCount > WEB_JOB_REASSIGN_LIMIT) {
        await input.store.updateRegressionTask(entry.rootPath, entry.task.id, {
          status: "failed",
          deviceLeaseId: null,
          jobSpec: specRecord({
            ...spec,
            deviceLeaseId: null,
            reassignCount,
            assignmentError: assignmentError(
              "unstable-assignment",
              `无法稳定分配：${reason}（已改派 ${WEB_JOB_REASSIGN_LIMIT} 次，任务终止）`,
              input.nowMs
            )
          }),
          expectStatuses: ["pending"]
        });
        continue;
      }

      const keepHost = spec.assignment === "manual";
      await input.store.updateRegressionTask(entry.rootPath, entry.task.id, {
        targetHostId: keepHost ? hostId : null,
        deviceSerial: null,
        deviceLeaseId: null,
        jobSpec: specRecord({
          ...spec,
          targetHostId: keepHost ? hostId : null,
          deviceSerial: null,
          deviceLeaseId: null,
          reassignCount,
          assignmentError: assignmentError(
            leaseExpired ? "no-device" : "host-offline",
            `${reason}；已放回${keepHost ? "目标 host 队列" : "全局队列"}重选`,
            input.nowMs
          )
        }),
        expectStatuses: ["pending"]
      });
    }
  }

  if (processed > 0) {
    await assignPendingWebJobs({
      store: input.store,
      env,
      nowMs: input.nowMs,
      runnerTtlMs,
      reservationTtlMs,
      rng: input.rng
    });
  }

  return processed;
}


async function pausedWebHostIds(store: ProjectStore): Promise<Set<string>> {
  try {
    const hosts = await store.listHosts();
    return new Set(hosts.filter((host) => host.queuePaused === true).map((host) => host.id));
  } catch {
    return new Set();
  }
}

export interface RecoverStaleWebJobsInput extends WebJobContext {
  nowMs: number;
  /** 进度/领取时间超过该窗口视为失联（0＝关闭时间判定，仅按实例存活判断）。 */
  staleMs: number;
  runnerTtlMs: number;
  /** 自身 host/实例：不回收本进程正在执行的任务。 */
  hostId?: string;
  instanceId?: string;
}

/**
 * 回收失联/过期的 web 领取：claimed/running 且（没有在线同实例 runner 或进度超窗）→ pending，
 * 清 claimed/started 字段并释放设备租约；下轮 assign 重新选机。
 */
export async function recoverStaleWebJobs(input: RecoverStaleWebJobsInput): Promise<number> {
  const [active, runners] = await Promise.all([
    input.store.listActiveWebJobs(),
    input.store.listWebRunners()
  ]);
  let recovered = 0;
  for (const entry of active) {
    const task = entry.task;
    if (
      input.hostId !== undefined &&
      input.instanceId !== undefined &&
      task.claimedHostId === input.hostId &&
      task.claimedInstanceId === input.instanceId
    ) {
      continue;
    }
    const hostId = task.claimedHostId ?? task.targetHostId;
    const runner = hostId === null ? undefined : runners.find((row) => row.hostId === hostId);
    const live =
      runner !== undefined &&
      runner.instanceId === task.claimedInstanceId &&
      isRunnerOnline(runner.lastSeenAt, input.nowMs, input.runnerTtlMs);
    const stamp = task.lastProgressAt ?? task.startedAt ?? task.claimedAt;
    const parsed = stamp === null ? Number.NaN : Date.parse(stamp);
    const staleByTime =
      input.staleMs <= 0
        ? false
        : !Number.isFinite(parsed) || input.nowMs - parsed > input.staleMs;
    if (live && !staleByTime) continue;

    if (hostId !== null && task.deviceSerial !== null) {
      await input.store.releaseDeviceLeases({
        hostId,
        taskId: task.id,
        serials: [task.deviceSerial]
      });
    }
    const spec = parseWebJobSpec(task.jobSpec);
    const reason = live ? "任务进度超时未更新" : "领取实例已失联/被接管";
    const updated = await input.store.updateRegressionTask(entry.rootPath, task.id, {
      status: "pending",
      claimedBy: null,
      claimedAt: null,
      claimedHostId: null,
      claimedInstanceId: null,
      startedAt: null,
      lastProgressAt: null,
      deviceLeaseId: null,
      ...(spec === null
        ? {}
        : {
            jobSpec: {
              ...spec,
              deviceLeaseId: null,
              assignmentError: {
                code: "stale-claim",
                message: `${reason}；已回池等待重新领取`,
                at: new Date(input.nowMs).toISOString()
              }
            } as Record<string, unknown>
          }),
      expectStatuses: ["claimed", "running"]
    });
    if (updated) recovered += 1;
  }
  return recovered;
}

/** 释放设备租约并撤销/回池任务（不删除历史行）。 */
export async function releaseWebJob(input: ReleaseWebJobInput): Promise<boolean> {
  const task = await input.store.getRegressionTask(input.rootPath, input.taskId);
  if (task === null) return false;
  const hostId = task.targetHostId ?? task.claimedHostId;
  if (hostId !== null) {
    await input.store.releaseDeviceLeases({ hostId, taskId: task.id });
  }
  if (input.reason === "cancelled") {
    const cancelled = await input.store.cancelRegressionTask({
      rootPath: input.rootPath,
      taskId: task.id,
      source: "panel",
      actor: input.actor ?? "web-job",
      actorHostId: null,
      note: "web job cancelled"
    });
    return cancelled !== null;
  }
  const spec = parseWebJobSpec(task.jobSpec);
  return input.store.updateRegressionTask(input.rootPath, task.id, {
    status: "pending",
    claimedBy: null,
    claimedAt: null,
    claimedHostId: null,
    claimedInstanceId: null,
    startedAt: null,
    lastProgressAt: null,
    deviceLeaseId: null,
    expectStatuses: ["pending", "claimed", "running"],
    ...(spec === null
      ? {}
      : {
          jobSpec: specRecord({
            ...spec,
            deviceLeaseId: null,
            assignmentError: assignmentError(input.reason, `任务已回池（${input.reason}）`, Date.now())
          })
        })
  });
}
