export interface WebJobContext {
  store: ProjectStore;
  env?: NodeJS.ProcessEnv;
}

export interface CreateWebJobInput extends WebJobContext {
  rootPath: string;
  assignment: "auto" | "manual";
  devicePinned?: boolean;
  targetHostId?: string | null;
  deviceSerial?: string | null;
  requirements: WebDispatchRequirements;
  excelAssetId: string;
  packageAssetId: string;
  materialsAssetId?: string | null;
  scriptSetId?: string | null;
  executionMode: WebJobExecutionMode;
  caseFilter: { modules: string[]; caseIds: string[] };
  retry?: number;
  priority?: number;
  createdBy?: string | null;
  allowStaleScript?: boolean;
  allowPartialUnresolved?: boolean;
  /** 惰性生成墙钟预算（ms）；缺省读 AOS_WEB_SCRIPT_GEN_TIMEOUT_MS（30000，0 关闭）。 */
  scriptGenerationTimeoutMs?: number;
  nowMs?: number;
  runnerTtlMs?: number;
  /** 预占租约 TTL（缺省＝`AOS_DEVICE_LEASE_MS`）。 */
  reservationTtlMs?: number;
  rng?: () => number;
}

export interface WebJobBinding {
  hostId: string;
  deviceSerial: string;
  score: number;
}

export interface WebJobScriptInfo {
  id: string;
  /** 缺省脚本集时由下发自动生成（含复用已有生成物）。 */
  autoGenerated: boolean;
  /** 过期脚本被重建时，原脚本集 id。 */
  rebuiltFrom: string | null;
  /** 本次是否新建了 scripts 资产（false＝复用）。 */
  created: boolean;
  ready: number;
  partial: number;
  unresolved: number;
  runnable: number;
}

